import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters"

describe("getGrams", () => {
    describe("извлечение явно указанного веса", () => {
        it.each([
            ["22,5 гр. Oil бесцветная (12936) ЕП", 22.5],
            ["22.5 гр Oil бесцветная (12936) ЕП", 22.5],
            ["12.0 гр Oil бесцветная (12936) ЕП", 12],
            ["12,0 гр Oil бесцветная (12936) ЕП", 12],
            ["61 гр. 38 мм бесцветная (4032) ЕП", 61],
            ["48гр. 38 мм бесцветная (4032) ЕП", 48],
            ["38 мм 48 гр бесцветная (4032) ЕП", 48],
            ["38 гр. 28 мм бесцветная (4032) ЕП", 38],
            ["28 мм 124гр бесцветная (4032) ЕП", 124],
            ["64 гр бесцветная ЕП", 64],
            ["(4032) 50гр Oil Крышка", 50],
        ])("%s → %s", (input, expected) => {
            expect(ih.getGrams(input)).toBe(expected);
        });
    });

    describe("пробелы и формат записи", () => {
        it.each([
            ["50 гр", 50],
            ["50гр", 50],
            ["50 гр.", 50],
            ["50гр.", 50],
            [" 50 гр. Крышка ", 50],
            ["50   гр. Крышка", 50],
            ["50,5гр", 50.5],
            ["50.5гр.", 50.5],
            ["0,5 гр", 0.5],
            ["0.25 гр", 0.25],
            ["1000 гр", 1000],
        ])("%s → %s", (input, expected) => {
            expect(ih.getGrams(input)).toBe(expected);
        });
    });

    describe("вес не указан", () => {
        it.each([
            "Товар без веса",
            "Крышка желтая СТС 29/13 1011 (5000) Oil BRC",
            "Крышка 28 мм",
            "Крышка 38 мм",
            "Товар (12936)",
            "Крышка 28 мм (4032) ЕП",
            "Oil бесцветная (12936) ЕП",
            "38 мм 28 мм",
        ])("%s → null", (input) => {
            expect(ih.getGrams(input)).toBeNull();
        });
    });

    describe("пустые и отсутствующие значения", () => {
        it.each([
            "",
            " ",
            null,
            undefined,
        ])("%s → null", (input) => {
            expect(ih.getGrams(input)).toBeNull();
        });
    });

    describe("некорректные значения", () => {
        it.each([
            "гр",
            "гр.",
            ",5 гр",
            ".5 гр",
            "abc гр",
        ])("%s → null", (input) => {
            expect(ih.getGrams(input)).toBeNull();
        });
    });
});