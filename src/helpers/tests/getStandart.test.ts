import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters";

describe("getStandart", () => {
    describe("Преформы", () => {
        it.each([
            ["Преформа 12 гр. 1881 бесцветная (21120) ЕПМ", ["1881"]],
            ["Преформа 22,5 гр. Oil бесцветная (13776) ЕП", ["Oil"]],
            ["Преформа 19,5 гр. 1810 бесцветная (13632) АТФ", ["1810"]],
            ["Преформа 24 гр.38 мм бесцветная (10176) ЕПМ", ["38"]],
            ["Преформа 81 гр.48 мм синяя (2600) ОП", ["48"]],
        ])("%s → %j", (input, expected) => {
            expect(ih.getStandart(input)).toEqual(expected);
        });
    });

    describe("Крышки", () => {
        it.each([
            ["Крышка желтая СТС 29/13 1011 (5000) Oil BRC", ["Oil"]],
            ["Крышка белая 1810 (28 мм) (5000) КТ", ["1810"]],
            ["Крышка синяя 066 (SС-1014) (6000) 1881 СК", ["1881"]],
            ["Крышка красная КВ-38 (2300) ЕК", ["КВ-38", "38"]],
            ["Крышка белая - КВ-50 БФ (1300) ЕК", ["КВ-50", "48"]],
            ["Крышка синяя - КВ-50 (1300) ЕК", ["КВ-50", "48"]],
            ["Крышка 38 мм синяя (3300) КТ", ["38"]],
            ["Крышка белая 1810 (28 мм) (5000) КТ", ["1810"]],
        ])("%s → %j", (input, expected) => {
            expect(ih.getStandart(input)).toEqual(expected);
        });
    });

    describe("Ручки", () => {
        it.each([
            ["Ручка синяя - РПБ-50 (650) ЕК", ["РПБ-50", "48"]],
            ["Ручка синяя(УСИЛ.) - РПБ-50 (600) ЕК", ["РПБ-50", "48"]],
            ["Ручка синяя Мешок d=28 mm (2000) УП", ["d=28"]],
            ["Ручка 38/2 мм синяя (1760) КТ", ["38"]],
            ["Ручка синяя РПБ-38 (800) ЕК", ["38"]],
        ])("%s → %j", (input, expected) => {
            expect(ih.getStandart(input)).toEqual(expected);
        });
    });

    describe("Пустые и некорректные значения", () => {
        it.each([null, undefined, ""])(
            "возвращает null для пустого значения: %s",
            (input) => {
                expect(ih.getStandart(input)).toBeNull();
            }
        );

        it("возвращает пустой массив, если стандарты не найдены", () => {
            expect(ih.getStandart("Преформа без стандарта")).toEqual([]);
        });
    });

    describe("Поиск числовых стандартов", () => {
        it.each([
            ["Преформа 138", "38"],
            ["Преформа 148", "48"],
            ["Преформа 11881", "1881"],
            ["Преформа 11810", "1810"],
        ])(
            "не находит стандарт %s внутри другого числа",
            (input, standard) => {
                expect(ih.getStandart(input)).not.toContain(standard);
            }
        );
    });

    describe("Дополнительные проверки getStandart", () => {
        describe("Определение стандартов по типу товара", () => {
            it("возвращает стандарты для колпачка", () => {
                expect(
                    ih.getStandart("Колпачок 1881 28 mm"),
                ).toEqual(["1881", "28 mm"]);
            });
        });

        describe("Поиск буквенно-цифровых стандартов", () => {
            it("находит BPF независимо от регистра", () => {
                expect(
                    ih.getStandart("Преформа bpf"),
                ).toContain("BPF");
            });

            it("находит Oil независимо от регистра", () => {
                expect(
                    ih.getStandart("Преформа OIL"),
                ).toContain("Oil");
            });

            it("находит SH у ручки", () => {
                expect(
                    ih.getStandart("Ручка SH"),
                ).toContain("SH");
            });

            it("не считает стандарт 1881 совпадением с 18810", () => {
                expect(
                    ih.getStandart("Крышка 18810"),
                ).not.toContain("1881");
            });
        });

        describe("Дополнительный стандарт 48", () => {
            it("не добавляет 48, если найден стандарт 50 и 48 уже присутствует", () => {
                const result = ih.getStandart(
                    "Крышка КВ-50 48",
                );

                expect(result?.filter((item) => item === "48")).toHaveLength(1);
            });

            it("не добавляет 48, если стандарт 50 не найден", () => {
                expect(
                    ih.getStandart("Крышка КВ-38"),
                ).not.toContain("48");
            });
        });

        describe("Уникальность результата", () => {
            it("не возвращает повторяющиеся стандарты", () => {
                const result = ih.getStandart(
                    "Крышка 1810 1810 1881",
                );

                expect(result).toEqual(["1810", "1881"]);
            });
        });
    });

    describe("Стандарт 50 дополнительно включает 48", () => {
        it.each([
            "Крышка белая - КВ-50 БФ (1300) ЕК",
            "Крышка синяя - КВ-50 (1300) ЕК",
            "Ручка синяя - РПБ-50 (650) ЕК",
            "Ручка синяя(УСИЛ.) - РПБ-50 (600) ЕК",
        ])("%s → содержит 50 и 48", (input) => {
            const result = ih.getStandart(input);

            expect(result).toContain("48");
            expect(result).toContain(
                result!.find((standard) => standard.includes("50"))
            );
        });
    });
});