import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters"

describe("getType", () => {
    it.each([
        ["Пробка 28 бело-желтый (4500) РП", "крышка"],
        ["КОЛПАЧОК 28 mm", "колпачок"],
        ["12 гр. 1881 бесцветная (21120) ЕПМ", "преформа"],
        ["22,5 гр. Oil бесцветная (13776) ЕП", "преформа"],
        ["60,5 гр. 38 мм бесцветная (4128) ПФ", "преформа"],
        ["Крышка белая 1810 (28 мм) (5000) КТ", "крышка"],
        ["Крышка желтая СТС 29/13 1011 (5000) Oil BRC", "крышка"],
        ["Крышка синяя 066 (SС-1014) (6000) 1881 СК", "крышка"],
        ["Крышка белая - КВ-50 БФ (1300) ЕК", "крышка"],
        ["Ручка 38/2 мм синяя (1760) КТ", "ручка"],
        ["Ручка синяя - РПБ-50 (650) ЕК", "ручка"],
        ["Ручка синяя Мешок d=28 mm (2000) УП", "ручка"],
    ])("определяет тип для номенклатуры «%s»", (nomenclature, expected) => {
        expect(ih.getType(nomenclature)).toBe(expected);
    });

    it.each([null, undefined, ""])(
        "возвращает null для пустой номенклатуры: %s",
        (nomenclature) => {
            expect(ih.getType(nomenclature)).toBeNull();
        }
    );
});