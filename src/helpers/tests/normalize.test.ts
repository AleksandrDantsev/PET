import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters";

describe("normalize", () => {
    describe("Приведение регистра", () => {
        it("приводит текст к нижнему регистру", () => {
            expect(ih.normalize("КРЫШКА БЕЛАЯ КТ")).toBe(
                "крышка белая кт",
            );
        });

        it("обрабатывает смешанный регистр", () => {
            expect(ih.normalize("Ручка Синяя - РПБ-50 ЕК")).toBe(
                "ручка синяя - рпб-50 ек",
            );
        });
    });

    describe("Замена ё на е", () => {
        it("заменяет ё на е", () => {
            expect(ih.normalize("Чёрная жёлтая")).toBe(
                "черная желтая",
            );
        });
    });

    describe("Замена знаков препинания пробелами", () => {
        it.each([
            ["Крышка (5000)", "крышка 5000"],
            ["Крышка [5000]", "крышка 5000"],
            ["Крышка {5000}", "крышка 5000"],
            ["Крышка, белая.", "крышка белая"],
            ['Крышка: "белая"', "крышка белая"],
            ["Крышка «белая»", "крышка белая"],
            ["Крышка 'белая'", "крышка белая"],
            ["Крышка; белая", "крышка белая"],
        ])("%s → %s", (input, expected) => {
            expect(ih.normalize(input)).toBe(expected);
        });

        it("не удаляет дефисы и слеши", () => {
            expect(ih.normalize("Ручка синяя - РПБ-50, 38/2 мм")).toBe(
                "ручка синяя - рпб-50 38/2 мм",
            );
        });
    });

    describe("Пробельные символы", () => {
        it("схлопывает несколько пробелов", () => {
            expect(ih.normalize("Крышка    белая     КТ")).toBe(
                "крышка белая кт",
            );
        });

        it("заменяет табуляции и переносы строк пробелами", () => {
            expect(ih.normalize("Крышка\tбелая\nКТ")).toBe(
                "крышка белая кт",
            );
        });

        it("удаляет пробелы в начале и конце", () => {
            expect(ih.normalize("   Крышка белая   ")).toBe(
                "крышка белая",
            );
        });
    });

    describe("Пустые и нестандартные значения", () => {
        it.each([
            [null, ""],
            [undefined, ""],
            ["", ""],
            ["   ", ""],
        ])("normalize(%s) → %s", (input, expected) => {
            expect(ih.normalize(input)).toBe(expected);
        });

        it("преобразует число в строку", () => {
            expect(ih.normalize(12345)).toBe("12345");
        });

        it("преобразует boolean в строку", () => {
            expect(ih.normalize(true)).toBe("true");
        });

        it("сохраняет цифры и единицы измерения", () => {
            expect(ih.normalize("60,5 гр. 38 мм (4128) ПФ")).toBe(
                "60 5 гр 38 мм 4128 пф",
            );
        });
    });

    describe("Реальная номенклатура", () => {
        it.each([
            [
                "12 гр. 1881 бесцветная (21120) ЕПМ",
                "12 гр 1881 бесцветная 21120 епм",
            ],
            [
                "Крышка белая 1810 (28 мм) (5000) КТ",
                "крышка белая 1810 28 мм 5000 кт",
            ],
            [
                "Ручка синяя(УСИЛ.) - РПБ-50 (600) ЕК",
                "ручка синяя усил - рпб-50 600 ек",
            ],
            [
                "Пробка 28 бело-желтый (4500) РП",
                "пробка 28 бело-желтый 4500 рп",
            ],
        ])("%s", (input, expected) => {
            expect(ih.normalize(input)).toBe(expected);
        });
    });
});
