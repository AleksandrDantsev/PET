import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters";

describe("getColor", () => {
    describe("Распознавание цветов", () => {
        it.each([
            ["Крышка бежевая", ["бежев"]],
            ["Крышка белая", ["бел"]],
            ["Преформа бесцветная", ["бесцветн"]],
            ["Крышка голубая", ["голуб"]],
            ["Крышка желтая", ["желт"]],
            ["Крышка зеленая", ["зелен"]],
            ["Крышка коричневая", ["коричнев"]],
            ["Крышка красная", ["красн"]],
            ["Крышка оранжевая", ["оранжев"]],
            ["Крышка розовая", ["розов"]],
            ["Крышка синяя", ["син"]],
            ["Крышка сиреневая", ["сиренев"]],
            ["Крышка ультрамарин", ["ультрамарин"]],
            ["Крышка фиолетовая", ["фиолетов"]],
            ["Крышка черная", ["черн"]],
            ["Крышка бирюзовая", ["бирюз"]],
        ])("%s → %j", (input, expected) => {
            expect(ih.getColor(input)).toEqual(expected);
        });
    });

    describe("Составные цвета", () => {
        it.each([
            ["Пробка бело-желтый", ["бело-желт"]],
            ["Крышка белая синяя", ["бел", "син"]],
            ["Крышка красная желтая", ["желт", "красн"]],
        ])("%s → %j", (input, expected) => {
            expect(ih.getColor(input)).toEqual(expected);
        });
    });

    describe("Нормализация текста", () => {
        it("приводит текст к нижнему регистру", () => {
            expect(ih.getColor("БЕЛАЯ КРЫШКА")).toEqual(["бел"]);
        });

        it("заменяет ё на е", () => {
            expect(ih.getColor("Крышка чёрная")).toEqual(["черн"]);
        });

        it("распознаёт цвет внутри длинной номенклатуры", () => {
            expect(
                ih.getColor("Крышка белая 1810 (28 мм) (5000) КТ")
            ).toEqual(["бел"]);
        });

        it("распознаёт цвет в начале, середине и конце строки", () => {
            expect(ih.getColor("СИНЯЯ крышка 38 мм")).toEqual(["син"]);
        });
    });

    describe("Пустые и некорректные значения", () => {
        it.each([null, undefined, ""])(
            "возвращает пустой массив для %s",
            (input) => {
                expect(ih.getColor(input)).toEqual([]);
            }
        );

        it("возвращает пустой массив, если цвет не найден", () => {
            expect(ih.getColor("Крышка 1810 (5000) КТ")).toEqual([]);
        });

        it("не определяет цвет по посторонним числам и символам", () => {
            expect(ih.getColor("1810 1881 38/2 мм (5000)")).toEqual([]);
        });
    });

    describe("Порядок результатов", () => {
        it("возвращает цвета в порядке массива colors, а не текста", () => {
            expect(ih.getColor("Синяя крышка белая")).toEqual([
                "бел",
                "син",
            ]);
        });

        it("не дублирует цвет при нескольких упоминаниях", () => {
            expect(ih.getColor("Белая крышка, белая ручка")).toEqual([
                "бел",
            ]);
        });
    });
});
