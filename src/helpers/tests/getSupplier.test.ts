import { describe, expect, it } from "vitest";
import { ih } from "../interchangeableFilters";

describe("getSupplier", () => {
    describe("Определение поставщика", () => {
        it.each([
            ["Крышка белая 1810 (28 мм) (5000) КТ", "КТ"],
            ["12 гр. 1881 бесцветная (21120) ЕПМ", "ЕПМ"],
            ["22,5 гр. Oil бесцветная (13776) ЕП", "ЕП"],
            ["60,5 гр. 38 мм бесцветная (4128) ПФ", "ПФ"],
            ["Крышка белая - КВ-50 БФ (1300) ЕК", "ЕК"],
            ["Крышка синяя - КВ-50 (1300) ЕК", "ЕК"],
            ["Крышка синяя 066 (SС-1014) (6000) 1881 СК", "СК"],
            ["Крышка желтая СТС 29/13 1011 (5000) Oil BRC", "BRC"],
            ["Ручка синяя - РПБ-50 (650) ЕК", "ЕК"],
            ["Ручка синяя(УСИЛ.) - РПБ-50 (600) ЕК", "ЕК"],
            ["Ручка синяя Мешок d=28 mm (2000) УП", "УП"],
            ["Пробка 28 бело-желтый (4500) РП", "РП"],
        ])("%s → %s", (input, expected) => {
            expect(ih.getSupplier(input)).toBe(expected);
        });
    });

    describe("Приоритет длинных обозначений", () => {
        it.each([
            ["Номенклатура ЕПМ", "ЕПМ"],
            ["Номенклатура ЕПБ", "ЕПБ"],
            ["Номенклатура УПР", "УПР"],
            ["Номенклатура БГА", "БГА"],
            ["Номенклатура Resilux", "Resilux"],
        ])("%s → %s", (input, expected) => {
            expect(ih.getSupplier(input)).toBe(expected);
        });
    });

    describe("Границы обозначений", () => {
        it("находит код в конце строки", () => {
            expect(ih.getSupplier("Крышка белая КТ")).toBe("КТ");
        });

        it("находит код в начале строки", () => {
            expect(ih.getSupplier("КТ Крышка белая")).toBe("КТ");
        });

        it("находит код между пробелами", () => {
            expect(ih.getSupplier("Крышка КТ белая")).toBe("КТ");
        });

        it("не находит код внутри другого буквенного обозначения", () => {
            expect(ih.getSupplier("Крышка ЕПМ")).toBe("ЕПМ");
            expect(ih.getSupplier("Крышка УПР")).toBe("УПР");
        });

        it("не считает цифры границей внутри буквенного кода", () => {
            expect(ih.getSupplier("Крышка КТ123")).toBeNull();
        });

        it("не находит латинский код внутри другого слова", () => {
            expect(ih.getSupplier("Крышка XBRC")).toBeNull();
        });
    });

    describe("Регистр", () => {
        it("игнорирует регистр кириллического обозначения", () => {
            expect(ih.getSupplier("Крышка кт")).toBe("КТ");
        });

        it("игнорирует регистр латинского обозначения", () => {
            expect(ih.getSupplier("Крышка resilux")).toBe("Resilux");
        });
    });

    describe("Несколько обозначений", () => {
        it("возвращает первое совпадение по порядку массива suppliers", () => {
            expect(ih.getSupplier("Крышка ЕПМ ЕК")).toBe("ЕПМ");
        });

        it("возвращает длинный код, если короткий входит в длинный", () => {
            expect(ih.getSupplier("Крышка УПР")).toBe("УПР");
        });
    });

    describe("Пустые и неизвестные значения", () => {
        it.each([null, undefined, ""])(
            "возвращает null для %s",
            (input) => {
                expect(ih.getSupplier(input)).toBeNull();
            },
        );

        it("возвращает null, если поставщик не найден", () => {
            expect(ih.getSupplier("Крышка белая 1810 (5000)")).toBeNull();
        });

        it("возвращает null для строки только с числами", () => {
            expect(ih.getSupplier("1810 1881 38/2 мм (5000)")).toBeNull();
        });
    });
});
