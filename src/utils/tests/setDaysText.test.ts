
import { describe, expect, it } from "vitest";
import { setDaysText } from "../normalize";

describe("setDaysText", () => {
    describe("пустые значения", () => {
        it.each([
            ["undefined", undefined],
            ["пустая строка", ""],
        ])("возвращает пустую строку для %s", (_description, value) => {
            expect(setDaysText(value)).toBe("");
        });
    });

    describe("числа от 1 до 10", () => {
        it.each([
            [1, "день"],
            [2, "дня"],
            [3, "дня"],
            [4, "дня"],
            [5, "дней"],
            [6, "дней"],
            [7, "дней"],
            [8, "дней"],
            [9, "дней"],
            [10, "дней"],
        ])("для %i возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("исключения от 11 до 14", () => {
        it.each([
            [11, "дней"],
            [12, "дней"],
            [13, "дней"],
            [14, "дней"],
        ])("для %i возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("составные числа", () => {
        it.each([
            [20, "дней"],
            [21, "день"],
            [22, "дня"],
            [23, "дня"],
            [24, "дня"],
            [25, "дней"],
            [26, "дней"],
            [27, "дней"],
            [28, "дней"],
            [29, "дней"],
            [30, "дней"],
            [31, "день"],
            [32, "дня"],
            [34, "дня"],
            [40, "дней"],
            [41, "день"],
            [51, "день"],
            [64, "дня"],
            [71, "день"],
            [82, "дня"],
            [91, "день"],
            [99, "дней"],
            [100, "дней"],
            [101, "день"],
            [102, "дня"],
            [104, "дня"],
            [105, "дней"],
            [111, "дней"],
            [112, "дней"],
            [113, "дней"],
            [114, "дней"],
            [121, "день"],
            [122, "дня"],
            [124, "дня"],
            [125, "дней"],
            [1000, "дней"],
            [1001, "день"],
            [1002, "дня"],
        ])("для %i возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("строковые значения", () => {
        it.each([
            ["1", "день"],
            ["2", "дня"],
            ["4", "дня"],
            ["5", "дней"],
            ["11", "дней"],
            ["14", "дней"],
            ["21", "день"],
            ["22", "дня"],
            ["25", "дней"],
            ["101", "день"],
        ])("для строки «%s» возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("отрицательные значения", () => {
        it.each([
            [-1, "день"],
            [-2, "дня"],
            [-3, "дня"],
            [-4, "дня"],
            [-5, "дней"],
            [-10, "дней"],
            [-11, "дней"],
            [-12, "дней"],
            [-13, "дней"],
            [-14, "дней"],
            [-20, "дней"],
            [-21, "день"],
            [-22, "дня"],
            [-24, "дня"],
            [-25, "дней"],
            [-101, "день"],
            [-102, "дня"],
            [-111, "дней"],
            [-114, "дней"],
            [-121, "день"],
        ])("для %i возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("дробные значения", () => {
        it.each([
            [1.5, "дней"],
            [2.5, "дней"],
            [10.5, "дней"],
            [-1.5, "дней"],
            [-2.5, "дней"],
        ])("для %s возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });

    describe("некорректные строковые значения", () => {
        it.each([
            ["abc", "дней"],
            ["не число", "дней"],
            [" ", "дней"],
        ])("для строки «%s» возвращает «%s»", (days, expected) => {
            expect(setDaysText(days)).toBe(expected);
        });
    });
});
