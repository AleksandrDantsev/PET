import { describe, expect, it } from "vitest";
import { normalize } from "../normalize";

describe("normalize", () => {
    describe("значение на входе", () => {
        it.each([
            ["обычная строка", "Ромашка", "ромашка"],
            ["пустая строка", "", ""],
            ["строка из пробелов", "   ", ""],
            ["число", 12345, "12345"],
            ["ноль", 0, "0"],
            ["отрицательное число", -123, "-123"],
            ["дробное число", 12.5, "12.5"],
            ["undefined", undefined, "undefined"],
            ["null", null, "null"],
        ])("%s", (_description, input, expected) => {
            expect(normalize(input as string | number | undefined)).toBe(
                expected,
            );
        });
    });

    describe("пробелы", () => {
        it.each([
            ["обычные пробелы", "  ООО   Ромашка  ", "ооо ромашка"],
            ["табуляция", "ООО\tРомашка", "ооо ромашка"],
            ["перенос строки", "ООО\nРомашка", "ооо ромашка"],
            ["смешанные пробелы", " ООО \t\n Ромашка ", "ооо ромашка"],
            ["неразрывный пробел", "ООО\u00A0Ромашка", "ооо ромашка"],
            [
                "несколько неразрывных пробелов",
                "ООО\u00A0\u00A0Ромашка",
                "ооо ромашка",
            ],
        ])("%s", (_description, input, expected) => {
            expect(normalize(input)).toBe(expected);
        });
    });

    describe("тире и дефисы", () => {
        it.each([
            ["hyphen-minus", "А-Б", "а-б"],
            ["hyphen", "А\u2010Б", "а-б"],
            ["figure dash", "А\u2012Б", "а-б"],
            ["en dash", "А\u2013Б", "а-б"],
            ["em dash", "А\u2014Б", "а-б"],
            ["minus sign", "А\u2212Б", "а-б"],
            [
                "разные виды тире",
                "А\u2010Б\u2012В\u2013Г\u2014Д\u2212Е",
                "а-б-в-г-д-е",
            ],
        ])("%s", (_description, input, expected) => {
            expect(normalize(input)).toBe(expected);
        });
    });

    describe("буква ё", () => {
        it.each([
            ["строчная ё", "ёлка", "елка"],
            ["заглавная Ё", "ЁЖ", "еж"],
            ["смешанный регистр", "Ёжик и ёлка", "ежик и елка"],
            ["несколько букв ё", "всё ещё ёж", "все еще еж"],
        ])("%s", (_description, input, expected) => {
            expect(normalize(input)).toBe(expected);
        });
    });

    describe("регистр", () => {
        it("приводит строку к нижнему регистру по умолчанию", () => {
            expect(normalize("ООО РОМАШКА")).toBe("ооо ромашка");
        });

        it("сохраняет регистр при toLowerRegister = false", () => {
            expect(normalize("ООО РОМАШКА", false)).toBe("ООО РОМАШКА");
        });

        it("сохраняет регистр, но заменяет ё на е", () => {
            expect(normalize("ЁЖ и Ёлка", false)).toBe("ЕЖ и Елка");
        });

        it("нормализует пробелы при сохранении регистра", () => {
            expect(normalize("  ООО   Ромашка  ", false)).toBe(
                "ООО Ромашка",
            );
        });

        it("нормализует тире при сохранении регистра", () => {
            expect(normalize("А\u2014Б", false)).toBe("А-Б");
        });
    });

    describe("комбинированные случаи", () => {
        it("применяет все преобразования одновременно", () => {
            expect(
                normalize("  ООО\u00A0Ёлка\u2014Сервис \t "),
            ).toBe("ооо елка-сервис");
        });

        it("не меняет обычную строку, уже приведённую к нужному виду", () => {
            expect(normalize("ооо ромашка-1")).toBe("ооо ромашка-1");
        });

        it("не изменяет исходную строку", () => {
            const input = "  ООО\u00A0РОМАШКА\u2014СЕРВИС  ";

            normalize(input);

            expect(input).toBe("  ООО\u00A0РОМАШКА\u2014СЕРВИС  ");
        });
    });
});