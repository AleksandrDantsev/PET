import { describe, expect, it } from "vitest";
import { capitalize } from "../normalize";

describe("capitalize", () => {
    describe("строки", () => {
        it.each([
            ["строчная первая буква", "ромашка", "Ромашка"],
            ["заглавная первая буква", "Ромашка", "Ромашка"],
            ["все буквы строчные", "привет мир", "Привет мир"],
            ["все буквы заглавные", "ПРИВЕТ МИР", "ПРИВЕТ МИР"],
            ["пустая строка", "", ""],
            ["строка из пробелов", "   ", "   "],
            ["один символ", "а", "А"],
            ["первая буква ё", "ёлка", "Ёлка"],
            ["первая буква латиницы", "hello", "Hello"],
            ["первая буква уже заглавная", "Hello", "Hello"],
        ])("%s", (_description, input, expected) => {
            expect(capitalize(input)).toBe(expected);
        });
    });

    describe("числа", () => {
        it.each([
            ["положительное целое", 123, "123"],
            ["ноль", 0, "0"],
            ["отрицательное число", -123, "-123"],
            ["дробное число", 12.5, "12.5"],
        ])("%s", (_description, input, expected) => {
            expect(capitalize(input)).toBe(expected);
        });
    });

    describe("специальные случаи", () => {
        it.each([
            ["пробел в начале", " ромашка", " ромашка"],
            ["цифра в начале", "123abc", "123abc"],
            ["дефис в начале", "-ромашка", "-ромашка"],
            ["знак препинания в начале", "!привет", "!привет"],
            ["эмодзи в начале", "😀привет", "😀привет"],
        ])("%s", (_description, input, expected) => {
            expect(capitalize(input)).toBe(expected);
        });
    });

    it("изменяет только первый символ строки", () => {
        expect(capitalize("пРИВЕТ")).toBe("ПРИВЕТ");
    });
});